/** One-time pull: self-host Stitch editorial imagery + generate LQIPs.
 * Usage: node scripts/pull-stitch-images.mjs
 * Reads the 5 desktop code.html files, downloads unique aida-public images
 * to public/editorial/, writes data/editorial.ts (typed src/alt/lqip map).
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = process.cwd();
const SCREENS = {
  home: 'stitch_ravya_luxury_parallax_showroom/ravya_fashion_redesigned_home/code.html',
  catalog: 'stitch_ravya_luxury_parallax_showroom/ravya_fashion_redesigned_catalog/code.html',
  brands: 'stitch_ravya_luxury_parallax_showroom/ravya_fashion_redesigned_brands/code.html',
  about: 'stitch_ravya_luxury_parallax_showroom/ravya_fashion_redesigned_about_story/code.html',
  visit: 'stitch_ravya_luxury_parallax_showroom/ravya_fashion_redesigned_visit_us/code.html',
};

const URL_RE = /https:\/\/lh3\.googleusercontent\.com\/aida-public\/[A-Za-z0-9_\-]+/g;

async function lqip(buf) {
  const tiny = await sharp(buf).resize(16, 16, { fit: 'inside' }).webp({ quality: 20 }).toBuffer();
  return `data:image/webp;base64,${tiny.toString('base64')}`;
}

function slug(alt, n) {
  const words = (alt || 'editorial')
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, '')
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 4)
    .join('-');
  return `${words || 'shot'}-${n}`;
}

const entries = [];
for (const [screen, rel] of Object.entries(SCREENS)) {
  const html = await fs.readFile(path.join(ROOT, rel), 'utf8');
  const urls = [...new Set(html.match(URL_RE) ?? [])];
  // capture data-alt per url (first occurrence)
  for (let i = 0; i < urls.length; i++) {
    const url = urls[i];
    const idx = html.indexOf(url);
    const window = html.slice(Math.max(0, idx - 600), idx);
    const altMatch = window.match(/data-alt="([^"]{0,200})"(?!.*data-alt=")/);
    const alt = altMatch ? altMatch[1] : `${screen} editorial ${i + 1}`;
    entries.push({ screen, url, alt, key: `${screen}_${slug(alt, i + 1)}` });
  }
}

console.log(`found ${entries.length} unique images`);
await fs.mkdir(path.join(ROOT, 'public', 'editorial'), { recursive: true });

const out = {};
let done = 0;
for (const e of entries) {
  const file = `${e.key}.jpg`;
  const dest = path.join(ROOT, 'public', 'editorial', file);
  try {
    await fs.access(dest);
    const buf = await fs.readFile(dest);
    out[e.key] = { src: `/editorial/${file}`, alt: e.alt, lqip: await lqip(buf) };
  } catch {
    const res = await fetch(e.url);
    if (!res.ok) throw new Error(`HTTP ${res.status} for ${e.url}`);
    const buf = Buffer.from(await res.arrayBuffer());
    const jpg = await sharp(buf).jpeg({ quality: 82 }).toBuffer();
    await fs.writeFile(dest, jpg);
    out[e.key] = { src: `/editorial/${file}`, alt: e.alt, lqip: await lqip(jpg) };
  }
  done++;
  if (done % 10 === 0) console.log(`  ${done}/${entries.length}`);
}

const ts =
  `/** Stitch editorial imagery, self-hosted. Generated by scripts/pull-stitch-images.mjs — do not edit. */\n` +
  `export interface EditorialImage { src: string; alt: string; lqip: string }\n\n` +
  `export const editorial: Record<string, EditorialImage> = ${JSON.stringify(out, null, 2)};\n`;
await fs.writeFile(path.join(ROOT, 'data', 'editorial.ts'), ts);
console.log(`wrote data/editorial.ts with ${Object.keys(out).length} entries`);
