/**
 * OPTIONAL one-time content production: fetch permissively-licensed stock
 * photos (Pexels) into raw/<productId>.jpg, then run `pnpm images` to build
 * AVIF/WebP + LQIP. The site build NEVER calls this script.
 *
 * Usage:
 *   PEXELS_API_KEY=your-key node scripts/fetch-images.mjs
 *
 * If raw/<id>.jpg already exists it is skipped. If no key is set, the script
 * exits and prepare-images.mjs will generate branded placeholders instead.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';

const RAW = 'raw';

async function main() {
  const key = process.env.PEXELS_API_KEY;
  if (!key) {
    console.log('PEXELS_API_KEY not set — skipping fetch. Placeholders will be generated by prepare-images.mjs.');
    return;
  }
  await fs.mkdir(RAW, { recursive: true });

  const src = await fs.readFile('data/products.ts', 'utf8');
  const ids = [];
  let m;
  const re = /image: '\/products\/([a-z0-9-]+)\.avif'/g;
  while ((m = re.exec(src))) ids.push(m[1]);

  const credits = {};
  try {
    Object.assign(credits, JSON.parse(await fs.readFile('data/image-credits.json', 'utf8')));
  } catch {
    /* fresh file */
  }

  for (const id of ids) {
    const out = path.join(RAW, `${id}.jpg`);
    try {
      await fs.access(out);
      console.log(`skip ${id} (exists)`);
      continue;
    }
    catch {
      /* fetch below */
    }
    const query = id.split('-').slice(1).join(' ').replace(/0\d$/, '').trim() || 'fashion clothing';
    const res = await fetch(
      `https://api.pexels.com/v1/search?query=${encodeURIComponent(query)}&per_page=1&orientation=portrait`,
      { headers: { authorization: key } },
    );
    if (!res.ok) {
      console.error(`pexels ${res.status} for ${id}`);
      continue;
    }
    const json = await res.json();
    const photo = json.photos?.[0];
    if (!photo) {
      console.log(`no result for ${id} (${query})`);
      continue;
    }
    const img = await fetch(photo.src.large2x ?? photo.src.large);
    const buf = Buffer.from(await img.arrayBuffer());
    await fs.writeFile(out, buf);
    credits[id] = { photographer: photo.photographer, url: photo.url, licence: 'Pexels License' };
    console.log(`fetched ${id}`);
  }

  await fs.writeFile('data/image-credits.json', JSON.stringify(credits, null, 2) + '\n');
  console.log('credits written to data/image-credits.json');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
